/**
 * How ranked mappers size chords: per key count and star range, the share of rows that are single
 * notes, 2-note chords, 3-note chords and so on (rice maps of training songs). Auto style sizes each
 * row's chord by its strength's percentile in the song, through this distribution, so the strongest
 * rows get the biggest chords and the song's overall mix matches the ranked maps'.
 */

/** lower edges of the star ranges (Star Rating Rebirth) */
export const CHORD_STAR_BINS = [0, 2, 3, 4, 5, 6, 7, 8, 9];

/** the ranked distribution for these keys and stars (nearest star range with data), or null */
export function chordTarget(keys: number, stars: number): number[] | null {
  const t = CHORD_TARGETS[keys];
  if (!t) return null;
  let b = 0;
  for (let i = 0; i < CHORD_STAR_BINS.length; i++) if (stars >= CHORD_STAR_BINS[i]) b = i;
  // the nearest star range with data, at most one range away (6K has data only around 4 stars)
  for (let d = 0; d <= 1; d++) {
    const lo = t[b - d], hi = t[b + d];
    if (lo) return lo;
    if (hi) return hi;
  }
  return null;
}

/** chord size for a row whose strength is at percentile p (0..1) of the song, through `dist` */
export function chordSizeAt(dist: number[], p: number): number {
  let acc = 0;
  for (let i = 0; i < dist.length; i++) { acc += dist[i]; if (p < acc) return i + 1; }
  return dist.length;
}

