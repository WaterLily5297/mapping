/**
 * Chord-size distributions of ranked rice maps, per key count and star range: the share of rows
 * that are single notes, 2-note chords, and so on. Training songs only (beatmap set id % 3 != 0),
 * each song once, maps with under 20% long notes and one red line. Writes src/automap/chordtargets.ts,
 * which the generator uses to size chords in auto style.
 *
 *   npx tsx scripts/bench/chord-targets.ts DATA_DIR [DATA_DIR...] [--dry]
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { parseOsu, getKeys, isLN } from '../../src/core/beatmap';
import { redLines } from '../../src/core/timing';
import { starRating } from '../../src/analysis/difficulty';
import { CHORD_STAR_BINS } from '../../src/automap/chordtargets';

const argv = process.argv.slice(2);
const dirs = argv.filter((a) => !a.startsWith('--'));
const KEYS = [4, 5, 6, 7, 8, 9, 10];
const binOf = (s: number) => { let b = 0; for (let i = 0; i < CHORD_STAR_BINS.length; i++) if (s >= CHORD_STAR_BINS[i]) b = i; return b; };
const sum: Record<number, number[][]> = {}, count: Record<number, number[]> = {};
for (const k of KEYS) { sum[k] = CHORD_STAR_BINS.map(() => new Array(k).fill(0)); count[k] = CHORD_STAR_BINS.map(() => 0); }
const seen = new Set<number>();
for (const dir of dirs) for (const set of readdirSync(dir).sort()) {
  const id = Number(set.split(' ')[0]);
  if (!Number.isFinite(id) || id % 3 === 0 || seen.has(id)) continue;
  seen.add(id);
  const p = join(dir, set);
  let files: string[];
  try { if (!statSync(p).isDirectory()) continue; files = readdirSync(p); } catch { continue; }
  for (const f of files.filter((x) => x.endsWith('.osu'))) {
    let m;
    try { m = parseOsu(readFileSync(join(p, f), 'utf8')); } catch { continue; }
    const k = getKeys(m);
    if (!KEYS.includes(k) || m.notes.length < 150 || redLines(m).length !== 1 || m.notes.filter(isLN).length / m.notes.length >= 0.2) continue;
    const by = new Map<number, number>();
    for (const n of m.notes) by.set(n.time, (by.get(n.time) ?? 0) + 1);
    const h = new Array(k).fill(0);
    for (const c of by.values()) h[Math.min(k, c) - 1]++;
    const tot = h.reduce((a, b) => a + b, 0);
    const b = binOf(starRating(m).stars);
    h.forEach((v, i) => { sum[k][b][i] += v / tot; });
    count[k][b]++;
  }
}
const out: Record<number, (number[] | null)[]> = {};
for (const k of KEYS) {
  out[k] = sum[k].map((s, b) => (count[k][b] >= 15 ? s.map((v) => +(v / count[k][b]).toFixed(4)) : null));
  console.log(`${k}K: maps per star range ${count[k].join(' ')}`);
  out[k].forEach((d, b) => { if (d) console.log(`   ${CHORD_STAR_BINS[b]}★+  ${d.map((v) => v.toFixed(2)).join(' ')}`); });
}
if (!argv.includes('--dry')) {
  const src = readFileSync('src/automap/chordtargets.ts', 'utf8');
  const i = src.indexOf('// ---- generated');
  writeFileSync('src/automap/chordtargets.ts', `${src.slice(0, i)}// ---- generated by scripts/bench/chord-targets.ts from ${seen.size} training songs (set id % 3 != 0)
export const CHORD_TARGETS: Record<number, (number[] | null)[]> = ${JSON.stringify(out)};
`);
  console.log('wrote src/automap/chordtargets.ts');
}
